window.uiLang = function () {
  var l = (document.documentElement.getAttribute("lang") || "en").toLowerCase().slice(0, 2);
  return window.UI_STRINGS[l] ? l : "en";
};
window.ui = function (key) {
  var L = window.UI_STRINGS[window.uiLang()] || {};
  return L[key] != null ? L[key] : (window.UI_STRINGS.en[key] != null ? window.UI_STRINGS.en[key] : key);
};

